package org.datakurator.ffdq.model.needs;

import org.datakurator.ffdq.rdf.RdfMapped;
import org.datakurator.ffdq.rdf.RdfReader;
import org.datakurator.ffdq.rdf.RdfWriter;
import org.eclipse.rdf4j.model.IRI;
import org.eclipse.rdf4j.model.Resource;

import org.datakurator.ffdq.model.context.Amendment;
import org.datakurator.ffdq.model.context.Measure;

import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

public class AmendmentPolicy implements RdfMapped {
	private String id = "urn:uuid:" + UUID.randomUUID();

    private UseCase useCase;
    private List<Amendment> amendments;

    /**
     * <p>Constructor for AmendmentPolicy.</p>
     */
    public AmendmentPolicy() { 
    	init();
    }
    
    /**
     * <p>Constructor for AmendmentPolicy.</p>
     *
     * @param id a {@link java.lang.String} object.
     * @param useCase a {@link org.datakurator.ffdq.model.needs.UseCase} object.
     */
    public AmendmentPolicy(String id, UseCase useCase) { 
    	init();
    	this.setId(id);
    	this.setUseCase(useCase);
    }
    
    private void init()  {
    	amendments = new ArrayList<Amendment>();
    }

    /**
     * <p>Getter for the field <code>id</code>.</p>
     *
     * @return a {@link java.lang.String} object.
     */
    public String getId() {
        return id;
    }
    
    /**
     * Override the autogenerated UUID with a provided id for this policy.
     *
     * @param id the provided id to use, ignored if null or blank
     */
    public void setId(String id) {
    	if (id!=null && id.length()>0) { 
    		this.id = id;
    	}
    }

    /**
     * <p>Getter for the field <code>useCase</code>.</p>
     *
     * @return a {@link org.datakurator.ffdq.model.needs.UseCase} object.
     */
    public UseCase getUseCase() {
        return useCase;
    }

    /**
     * <p>Setter for the field <code>useCase</code>.</p>
     *
     * @param useCase a {@link org.datakurator.ffdq.model.needs.UseCase} object.
     */
    public void setUseCase(UseCase useCase) {
        this.useCase = useCase;
    }

    /**
     * <p>getEnhancementInContext.</p>
     *
     * @return a {@link java.util.List} object.
     */
    public List<Amendment> getEnhancementInContext() {
        return amendments;
    }

    /**
     * <p>addAmendment.</p>
     *
     * @param ce a {@link org.datakurator.ffdq.model.context.Amendment} object.
     */
    public void addAmendment(Amendment ce) {
        this.amendments.add(ce);
    }

    /**
     * <p>getLabel.</p>
     *
     * @return a generated label
     */
	public String getLabel() {
		StringBuilder labelBuilder = new StringBuilder();
		labelBuilder.append("AmendmentPolicy: (");
		labelBuilder.append(amendments.size()).append(") amendments ");
		labelBuilder.append(" in UseCase ");
		labelBuilder.append(useCase.getLabel());
		return labelBuilder.toString();
	}

    // ---- RDF mapping (explicit RDF4J; replaces the RDFBeans annotations) ----

    /** The RDF type of this class. */
    public static final String RDF_TYPE = "bdqffdq:AmendmentPolicy";

    /**
     * Write this object's own properties (and those of its superclasses) as RDF.
     *
     * @param w the writer
     * @param s the subject
     */
    protected void writeRdfProperties(RdfWriter w, Resource s) {
        w.value(s, "bdqffdq:hasUseCase", getUseCase());
        w.values(s, "bdqffdq:includedInPolicy", getEnhancementInContext());
        w.value(s, "rdfs:label", getLabel());
    }

    /** {@inheritDoc} */
    @Override
    public Resource writeRdf(RdfWriter w) {
        IRI s = RdfWriter.subject(getId(), null);
        if (w.begin(this)) {
            w.type(s, RDF_TYPE);
            writeRdfProperties(w, s);
        }
        return s;
    }

    /**
     * Read this object's own properties (and those of its superclasses) from RDF.
     *
     * @param r the reader
     * @param s the subject
     */
    protected void readRdfProperties(RdfReader r, Resource s) {
        setUseCase(r.read(s, "bdqffdq:hasUseCase", UseCase::readRdf));
        this.amendments = new java.util.ArrayList<>(r.readAll(s, "bdqffdq:includedInPolicy", Amendment::readRdf));
        // rdfs:label: computed by getLabel() from other properties; not read.
    }

    /**
     * Read a AmendmentPolicy from RDF.
     *
     * @param r the reader
     * @param s the subject
     * @return the AmendmentPolicy, the same instance each time for the same subject
     */
    public static AmendmentPolicy readRdf(RdfReader r, Resource s) {
        Object cached = r.cached(s);
        if (cached instanceof AmendmentPolicy) { return (AmendmentPolicy) cached; }
        AmendmentPolicy o = r.remember(s, new AmendmentPolicy());
        o.setId(s.stringValue());
        o.readRdfProperties(r, s);
        return o;
    }

}
